#!/bin/bash
set -euo pipefail

export PGPASSWORD="${POSTGRES_SUPERUSER_PASSWORD}"

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_SUPERUSER}" --dbname "${POSTGRES_BOOTSTRAP_DB}" <<-EOSQL
DO
\$do\$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${KNOWLEDGE_DB_USERNAME}') THEN
        EXECUTE format('CREATE USER %I WITH PASSWORD %L', '${KNOWLEDGE_DB_USERNAME}', '${KNOWLEDGE_DB_PASSWORD}');
    ELSE
        EXECUTE format('ALTER USER %I WITH PASSWORD %L', '${KNOWLEDGE_DB_USERNAME}', '${KNOWLEDGE_DB_PASSWORD}');
    END IF;
END
\$do\$;
EOSQL

if ! psql -tA --username "${POSTGRES_SUPERUSER}" --dbname "${POSTGRES_BOOTSTRAP_DB}" -c "SELECT 1 FROM pg_database WHERE datname = '${KNOWLEDGE_DB_NAME}'" | grep -q 1; then
    psql -v ON_ERROR_STOP=1 --username "${POSTGRES_SUPERUSER}" --dbname "${POSTGRES_BOOTSTRAP_DB}" -c "CREATE DATABASE \"${KNOWLEDGE_DB_NAME}\" OWNER \"${KNOWLEDGE_DB_USERNAME}\""
fi

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_SUPERUSER}" --dbname "${KNOWLEDGE_DB_NAME}" <<-EOSQL
REVOKE ALL ON DATABASE "${KNOWLEDGE_DB_NAME}" FROM PUBLIC;
GRANT ALL PRIVILEGES ON DATABASE "${KNOWLEDGE_DB_NAME}" TO "${KNOWLEDGE_DB_USERNAME}";
EOSQL
